bool check_repeat_num(ll x, ll y) {
    ll n = x + y * 1e5;
    vector<bool> flags(9, false);
    while (n) {
        if (const int w = n % 10) {
            if (flags[w]) {
                return false;
            }
            flags[w] = true;
        }
        n /= 10;
    }
    return true;
}


int main() {
    ll n = 0;
    while (scanf("%lld", &n) && n) {
        for (ll i = 1; i < 1e5; i++) {
            ll l = n * i;
            if (l >= 1e5) {
                break;
            }
            if (!check_repeat_num(l, i)) {
                printf("%05lld/%05lld=%lld\n", l, i, n);
            }
        }
        putchar('\n');
    }
}


